"""Step 0 of the decorating plan: audit the existing .blend files without changing them.

    /Applications/Blender.app/Contents/MacOS/Blender -b -P scripts/verify_assets.py

Opens every build/*.blend read-only, lists each object (type, world origin, size, triangles,
materials) and checks what the decorating steps rely on: the plate's origin at its exact
centre, the cake and cupcake sizes, the slab's marble. Writes docs/asset_status.md and
build/renders/audit/contact_sheet.png (a grid of the existing review renders).
"""
import glob
import os
import sys

import bpy

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "blender"))
import common as C  # noqa: E402
import imaging as I  # noqa: E402

DOC = os.path.join(C.REPO, "docs", "asset_status.md")
SHEET = os.path.join(C.BUILD, "renders", "audit", "contact_sheet.png")


def world_size(obj):
    if obj.type != "MESH":
        return None
    lo, hi = C.world_bounds([obj.name])
    return [round(h - l, 4) for l, h in zip(lo, hi)], [round((h + l) / 2, 4) for l, h in zip(lo, hi)]


def audit(path):
    bpy.ops.wm.open_mainfile(filepath=path)
    rows, notes = [], []
    for obj in sorted(bpy.data.objects, key=lambda o: o.name):
        size = world_size(obj)
        tris = C.triangle_count([obj])[0] if obj.type == "MESH" else 0
        loc = [round(v, 4) for v in obj.matrix_world.translation]
        mats = ",".join(m.name for m in getattr(obj.data, "materials", []) if m) if obj.data else ""
        rows.append((obj.name, obj.type, loc, size[0] if size else "", tris, mats))
        if obj.name == "TurntablePlate" and size:
            off = max(abs(a - b) for a, b in zip(loc[:2], size[1][:2]))
            notes.append(f"TurntablePlate origin vs bounds centre (XY): {off * 1000:.3f} mm "
                         + ("OK" if off < 1e-4 else "MISMATCH"))
    return rows, notes


def main():
    blends = sorted(glob.glob(os.path.join(C.BUILD, "*.blend")))
    out = ["# Asset status (audit, generated by scripts/verify_assets.py)", "",
           "Read-only audit of the existing `.blend` files. Nothing here was changed. "
           "Mismatches with the decorating plan are listed at the end.", ""]
    all_notes = []
    for path in blends:
        rows, notes = audit(path)
        name = os.path.basename(path)
        all_notes += [f"{name}: {n}" for n in notes]
        out += [f"## {name}", "", "| Object | Type | Origin (m) | Size (m) | Tris | Materials |",
                "| --- | --- | --- | --- | --- | --- |"]
        for r in rows:
            if r[1] in ("MESH", "EMPTY", "CURVE"):
                out.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} |")
        out.append("")
    out += ["## Checks", ""] + [f"- {n}" for n in all_notes] + [""]
    out += ["## Mismatches with the decorating plan", "",
            "- The plan says `moulds.py` holds the cake and cupcake in four bake states. They are in "
            "`build/muffin_tin_<state>.blend` and `build/cake_tin_<state>.blend` (one file per dish and "
            "state), plus `build/cake_turnout.blend` (the turned-out golden cake). cake_maps.py reads those.",
            "- There is no `studio.py` top-down sprite camera. New scripts place a temporary orthographic "
            "camera from `camera.json` `plate_topdown`/`topdown` conventions via `deco_common.sprite_camera()` "
            "and keep `studio.use()` for the lights and world.",
            "- The plan names a `transition.py`. The oven-to-stand move already exists in the app "
            "(`StationMoveView`, `TongsView`, `station_export.py`), so it is skipped.",
            "- The plan's `build/stage.blend` does not exist; the stage is assembled from `slab.blend`, "
            "`cakestand.blend` and `oven.blend` (as `slab.py` does). focus.py does the same.", ""]
    with open(DOC, "w") as f:
        f.write("\n".join(out))
    pngs = sorted(glob.glob(os.path.join(C.BUILD, "renders", "cakestand", "*.png")))[:6] + \
        sorted(glob.glob(os.path.join(C.BUILD, "renders", "slab", "*.png")))[:3] + \
        sorted(glob.glob(os.path.join(C.BUILD, "renders", "moulds", "**", "*.png"), recursive=True))[:3]
    if pngs:
        os.makedirs(os.path.dirname(SHEET), exist_ok=True)
        I.grid(pngs, SHEET, columns=4)
    print(f"[audit] {len(blends)} files -> {DOC}")


main()
